/**
 * Códigos de error estables que la API devuelve en `error.code` (Q-003).
 *
 * Son parte del contrato con el frontend, que traduce cada código al mensaje que ve el usuario:
 * no se renombran ni se reutilizan para otro significado. Cada valor es igual a su nombre.
 */
export enum ErrorCode {
  // Autenticación
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  // D-12 (F2-T04): contraseña correcta, pero el correo aún no está verificado.
  EMAIL_NOT_VERIFIED = 'EMAIL_NOT_VERIFIED',
  SESSION_REQUIRED = 'SESSION_REQUIRED',
  INVALID_SESSION = 'INVALID_SESSION',
  // El token de acceso caducó (F2-T02): el frontend llama a POST /auth/refresh y repite la petición.
  SESSION_EXPIRED = 'SESSION_EXPIRED',

  // Permisos
  INSUFFICIENT_PERMISSIONS = 'INSUFFICIENT_PERMISSIONS',
  // F2-T05: nadie cambia su propio rol ni desactiva su propia cuenta.
  CANNOT_MANAGE_OWN_ACCOUNT = 'CANNOT_MANAGE_OWN_ACCOUNT',
  // Petición que modifica datos enviada desde un origen fuera de la lista blanca (CSRF, F2-T07).
  ORIGIN_NOT_ALLOWED = 'ORIGIN_NOT_ALLOWED',

  // Recursos inexistentes, o de otro tenant: se responde igual para no revelar que existen.
  LEAD_NOT_FOUND = 'LEAD_NOT_FOUND',
  LEAD_STATUS_NOT_FOUND = 'LEAD_STATUS_NOT_FOUND',
  CONTACT_NOT_FOUND = 'CONTACT_NOT_FOUND',
  COMPANY_CONTACT_NOT_FOUND = 'COMPANY_CONTACT_NOT_FOUND',
  USER_NOT_FOUND = 'USER_NOT_FOUND',
  INVITATION_NOT_FOUND = 'INVITATION_NOT_FOUND',
  PRODUCT_NOT_FOUND = 'PRODUCT_NOT_FOUND',
  RECORD_NOT_FOUND = 'RECORD_NOT_FOUND',
  ROUTE_NOT_FOUND = 'ROUTE_NOT_FOUND',

  // Conflictos con el estado actual de los datos
  EMAIL_ALREADY_IN_USE = 'EMAIL_ALREADY_IN_USE',
  DEFAULT_LEAD_STATUS_MISSING = 'DEFAULT_LEAD_STATUS_MISSING',
  DEFAULT_LEAD_STATUS_REQUIRED = 'DEFAULT_LEAD_STATUS_REQUIRED',
  COMPANY_CONTACT_HAS_CONTACTS = 'COMPANY_CONTACT_HAS_CONTACTS',
  DOCUMENT_ALREADY_REGISTERED = 'DOCUMENT_ALREADY_REGISTERED',
  LEAD_STATUS_ORDER_TAKEN = 'LEAD_STATUS_ORDER_TAKEN',
  LEAD_STATUS_IN_USE = 'LEAD_STATUS_IN_USE',
  DEFAULT_LEAD_STATUS_CANNOT_BE_DELETED = 'DEFAULT_LEAD_STATUS_CANNOT_BE_DELETED',

  // Entrada inválida
  VALIDATION_FAILED = 'VALIDATION_FAILED',
  MISSING_REQUIRED_DATA = 'MISSING_REQUIRED_DATA',
  MALFORMED_JSON = 'MALFORMED_JSON',
  INVALID_REQUEST_BODY = 'INVALID_REQUEST_BODY',
  PAYLOAD_TOO_LARGE = 'PAYLOAD_TOO_LARGE',
  INVALID_LEAD_STATUS = 'INVALID_LEAD_STATUS',
  ASSIGNED_USER_NOT_FOUND = 'ASSIGNED_USER_NOT_FOUND',
  INVALID_COMPANY_CONTACT = 'INVALID_COMPANY_CONTACT',
  INVALID_DOCUMENT_NUMBER = 'INVALID_DOCUMENT_NUMBER',
  DOCUMENT_TYPE_REQUIRED = 'DOCUMENT_TYPE_REQUIRED',
  OWNER_NOT_FOUND = 'OWNER_NOT_FOUND',
  // Dinero y porcentajes exactos (F3-T01, H21).
  INVALID_MONEY_AMOUNT = 'INVALID_MONEY_AMOUNT',
  INVALID_PERCENTAGE = 'INVALID_PERCENTAGE',
  INVALID_QUANTITY = 'INVALID_QUANTITY',
  // Fórmulas de precio (F3-T03).
  INVALID_FORMULA = 'INVALID_FORMULA',
  INVALID_FORMULA_VARIABLE = 'INVALID_FORMULA_VARIABLE',
  FORMULA_EVALUATION_FAILED = 'FORMULA_EVALUATION_FAILED',
  // Productos (F3-T02): sin precio fijo ni fórmula, o con una fórmula que no es de la empresa.
  PRODUCT_PRICE_REQUIRED = 'PRODUCT_PRICE_REQUIRED',
  INVALID_PRODUCT_FORMULA = 'INVALID_PRODUCT_FORMULA',
  // Política de contraseñas (D-11, F2-T03).
  PASSWORD_TOO_WEAK = 'PASSWORD_TOO_WEAK',
  PASSWORD_BREACHED = 'PASSWORD_BREACHED',
  // Enlace de verificación, recuperación o invitación que no existe, caducó o ya se usó (F2-T04).
  INVALID_ACCOUNT_TOKEN = 'INVALID_ACCOUNT_TOKEN',
  DEFAULT_LEAD_STATUS_MUST_BE_OPEN = 'DEFAULT_LEAD_STATUS_MUST_BE_OPEN',
  LEAD_STATUS_LIST_MISMATCH = 'LEAD_STATUS_LIST_MISMATCH',
  INVALID_FILTERS_FORMAT = 'INVALID_FILTERS_FORMAT',
  FILTER_FIELD_NOT_ALLOWED = 'FILTER_FIELD_NOT_ALLOWED',
  FILTER_OPERATOR_NOT_ALLOWED = 'FILTER_OPERATOR_NOT_ALLOWED',
  INVALID_FILTER_VALUE = 'INVALID_FILTER_VALUE',
  SORT_FIELD_NOT_ALLOWED = 'SORT_FIELD_NOT_ALLOWED',

  // Límite de peticiones superado
  TOO_MANY_REQUESTS = 'TOO_MANY_REQUESTS',

  // Una dependencia (la base de datos) no responde: la instancia no está lista.
  SERVICE_UNAVAILABLE = 'SERVICE_UNAVAILABLE',

  // Fallo no previsto: el detalle solo queda en el servidor.
  INTERNAL_ERROR = 'INTERNAL_ERROR',
}
